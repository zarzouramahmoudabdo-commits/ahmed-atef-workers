-- أحمد عاطف لإدارة العمال — المخطط الأساسي
-- الأموال كلها NUMERIC(12,2). كل شهر ميلادي مستقل (يُحدد بنطاق work_date/تاريخ العملية).
create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null check (role in ('admin','accountant')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
$$;
create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','accountant'))
$$;

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create or replace function public.set_created_by() returns trigger language plpgsql as $$
begin new.created_by = auth.uid(); return new; end $$;

create table public.workers (
  id uuid primary key default gen_random_uuid(),
  worker_no bigint generated by default as identity unique,
  full_name text not null check (length(btrim(full_name)) > 0),
  phone text,
  whatsapp text,
  start_date date,
  daily_rate numeric(12,2) not null check (daily_rate >= 0),
  overtime_rate numeric(12,2) not null check (overtime_rate >= 0),
  notes text,
  status text not null default 'active' check (status in ('active','archived')),
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index workers_name_idx on public.workers (full_name);

-- سجل الحضور: صف واحد لكل عامل/يوم. غياب الصف = "غير مسجل".
-- السهرة داخل نفس الصف، والقيود تمنع سهرة بدون حضور حتى مع طلبات متزامنة.
create table public.attendance (
  id uuid primary key default gen_random_uuid(),
  worker_id uuid not null references public.workers(id) on delete restrict,
  work_date date not null,
  status text not null check (status in ('present','absent')),
  daily_rate_used numeric(12,2) not null default 0 check (daily_rate_used >= 0),
  overtime boolean not null default false,
  overtime_rate_used numeric(12,2) not null default 0 check (overtime_rate_used >= 0),
  notes text,
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint attendance_unique_day unique (worker_id, work_date),
  constraint overtime_requires_present check (not overtime or status = 'present'),
  constraint absent_has_no_pay check (status = 'present' or (daily_rate_used = 0 and overtime_rate_used = 0)),
  constraint overtime_rate_consistent check (overtime or overtime_rate_used = 0)
);
create index attendance_date_idx on public.attendance (work_date, worker_id);

create table public.advances (
  id uuid primary key default gen_random_uuid(),
  worker_id uuid not null references public.workers(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  adv_date date not null,
  reason text,
  voided_at timestamptz, voided_by uuid, void_reason text,
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.deductions (
  id uuid primary key default gen_random_uuid(),
  worker_id uuid not null references public.workers(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  ded_date date not null,
  reason text not null check (length(btrim(reason)) > 0),
  notes text,
  voided_at timestamptz, voided_by uuid, void_reason text,
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.payments (
  id uuid primary key default gen_random_uuid(),
  worker_id uuid not null references public.workers(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  pay_date date not null,
  method text,
  note text,
  voided_at timestamptz, voided_by uuid, void_reason text,
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index advances_idx on public.advances (worker_id, adv_date);
create index deductions_idx on public.deductions (worker_id, ded_date);
create index payments_idx on public.payments (worker_id, pay_date);

create table public.audit_logs (
  id bigint generated always as identity primary key,
  table_name text not null,
  record_id uuid,
  action text not null,
  old_data jsonb,
  new_data jsonb,
  user_id uuid,
  created_at timestamptz not null default now()
);

create or replace function public.audit_row() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit_logs(table_name, record_id, action, old_data, new_data, user_id)
  values (tg_table_name,
          coalesce((case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end)->>'id','')::uuid,
          tg_op,
          case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,
          case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end,
          auth.uid());
  return null;
end $$;

do $$ declare t text; begin
  foreach t in array array['workers','attendance','advances','deductions','payments'] loop
    execute format('create trigger %I_touch before update on public.%I for each row execute function public.touch_updated_at()', t, t);
    execute format('create trigger %I_creator before insert on public.%I for each row execute function public.set_created_by()', t, t);
    execute format('create trigger %I_audit after insert or update or delete on public.%I for each row execute function public.audit_row()', t, t);
  end loop;
end $$;
